// Builds supabase/seed-questions.sql from supabase/questions/*.json.
// Usage: npm run seed      (re-run after editing any JSON file; the SQL is safe to run again, it skips duplicates)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'supabase', 'questions')
const SUBJECTS = ['eng', 'mat', 'phy', 'chm', 'bio', 'gov', 'eco', 'com', 'agr', 'acc', 'mkt', 'lit', 'irk', 'crk', 'hec', 'cst', 'geo']
const esc = (s) => String(s).replace(/'/g, "''")

export function validate(subject, list) {
  const errors = []
  const seen = new Set()
  list.forEach((q, i) => {
    const at = `${subject}[${i}]`
    if (!q.q || typeof q.q !== 'string') errors.push(`${at}: missing question text`)
    if (!Array.isArray(q.o) || q.o.length !== 4) errors.push(`${at}: needs exactly 4 options`)
    else if (new Set(q.o.map((x) => String(x).trim().toLowerCase())).size !== 4) errors.push(`${at}: duplicate options`)
    if (!Number.isInteger(q.a) || q.a < 0 || q.a > 3) errors.push(`${at}: answer must be 0 to 3`)
    if (!q.e) errors.push(`${at}: missing explanation`)
    const key = (q.q || '').toLowerCase()
    if (seen.has(key)) errors.push(`${at}: duplicate question`)
    seen.add(key)
  })
  return errors
}

export function build() {
  const rows = []
  const errors = []
  for (const s of SUBJECTS) {
    const list = JSON.parse(fs.readFileSync(path.join(dir, `${s}.json`), 'utf8'))
    errors.push(...validate(s, list))
    for (const q of list) rows.push(`('${s}','${esc(q.q)}','${esc(JSON.stringify(q.o))}'::jsonb,${q.a},'${esc(q.e)}')`)
  }
  if (errors.length) throw new Error('Question data problems:\n' + errors.join('\n'))
  return (
    '-- Generated by `npm run seed` from supabase/questions/*.json. Do not edit by hand.\n' +
    '-- Safe to run more than once: existing questions are skipped.\n' +
    '-- It first makes sure the database accepts all 17 subjects (the same change as migrate-subjects.sql), so it works on its own.\n' +
    "alter table public.questions drop constraint if exists questions_subject_check;\n" +
    "alter table public.questions add constraint questions_subject_check check (subject in (" + SUBJECTS.map((s) => `'${s}'`).join(',') + "));\n\n" +
    'insert into public.questions (subject, body, options, answer, explanation) values\n' +
    rows.join(',\n') +
    '\non conflict (subject, body) do nothing;\n\n' +
    '-- Check: one row per subject with how many questions it now has (every subject should show 35 or more).\n' +
    'select subject, count(*) as questions from public.questions group by subject order by subject;\n'
  )
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(root, 'supabase', 'seed-questions.sql'), build())
  console.log(`Wrote seed-questions.sql with ${build().split('\n').filter((l) => l.startsWith("('")).length} questions`)
}
